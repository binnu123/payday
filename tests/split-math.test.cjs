const assert = require('node:assert/strict');
const { shares, balances, simplify } = require('../www/split-math.js');
const people = [{ id: 'a' }, { id: 'b' }, { id: 'c' }];
assert.deepEqual(shares(100, people, 'equal').map(s => s.cents), [34, 33, 33]);
assert.deepEqual(shares(101, [{ id: 'a', value: 5000 }, { id: 'b', value: 5000 }], 'percentage').map(s => s.cents), [51, 50]);
assert.throws(() => shares(100, [{ id: 'a', value: 50 }, { id: 'b', value: 49 }], 'exact'));
const expenses = [{ payers: [{ id: 'a', cents: 70 }, { id: 'b', cents: 30 }], shares: shares(100, people, 'equal') }];
let net = balances(people, expenses, []);
assert.deepEqual(net, { a: 36, b: -3, c: -33 });
net = balances(people, expenses, [{ from: 'c', to: 'a', cents: 10 }]);
assert.deepEqual(net, { a: 26, b: -3, c: -23 });
assert.deepEqual(simplify(net), [{ from: 'b', to: 'a', cents: 3 }, { from: 'c', to: 'a', cents: 23 }]);
assert.deepEqual(balances(people, [], []), { a: 0, b: 0, c: 0 });
assert.deepEqual(shares(100, [{ id: 'a', value: 1 }, { id: 'b', value: 2 }], 'shares').map(s => s.cents), [33, 67]);
assert.throws(() => shares(100, [{ id: 'a', value: 9999 }, { id: 'b', value: 0 }], 'percentage'));
assert.deepEqual(balances(people, expenses, [{ from: 'b', to: 'a', cents: 3 }, { from: 'c', to: 'a', cents: 33 }]), { a: 0, b: 0, c: 0 });
const amended = [{ payers: [{ id: 'a', cents: 90 }], shares: shares(90, people, 'equal') }];
assert.deepEqual(balances(people, amended, []), { a: 60, b: -30, c: -30 });
assert.throws(() => balances(people, [{ payers: [{ id: 'a', cents: 10 }], shares: [{ id: 'b', cents: 9 }] }], []));
